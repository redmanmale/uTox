#!/bin/sh
set -e -u -x

. ./extra/ci/env.sh

STATIC_ALL="${STATIC_ALL:-OFF}"
STATIC_TOXCORE="${STATIC_TOXCORE:-OFF}"
ENABLE_DBUS="${ENABLE_DBUS:-ON}"
ENABLE_FILTERAUDIO="${ENABLE_FILTERAUDIO:-ON}"
ENABLE_WERROR="${ENABLE_WERROR:-ON}"
ENABLE_TESTS="${ENABLE_TESTS:-ON}"

set -- \
  -DCMAKE_INCLUDE_PATH="$CACHE_DIR/usr/include" \
  -DCMAKE_LIBRARY_PATH="$CACHE_DIR/usr/lib" \
  -DCMAKE_PREFIX_PATH="$CACHE_DIR/usr" \
  -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
  -DSTATIC_ALL="$STATIC_ALL" \
  -DSTATIC_TOXCORE="$STATIC_TOXCORE" \
  -DENABLE_TESTS="$ENABLE_TESTS" \
  -DENABLE_WERROR="$ENABLE_WERROR" \
  -DENABLE_FILTERAUDIO="$ENABLE_FILTERAUDIO" \
  -DENABLE_DBUS="$ENABLE_DBUS"

if [ -n "${ENABLE_ASAN:-}" ]; then
  set -- "$@" -DENABLE_ASAN="$ENABLE_ASAN"
fi
if [ -n "${ENABLE_UBSAN:-}" ]; then
  set -- "$@" -DENABLE_UBSAN="$ENABLE_UBSAN"
fi
if [ -n "${ENABLE_TSAN:-}" ]; then
  set -- "$@" -DENABLE_TSAN="$ENABLE_TSAN"
fi
if [ -n "${ENABLE_LTO:-}" ]; then
  set -- "$@" -DENABLE_LTO="$ENABLE_LTO"
fi

cmake . "$@"
make
./run_tests.sh
